#!/usr/bin/env bash
# Builds the Rust backend of zeclib for the host platform, stages the static
# library where the Go package links it from, and regenerates the Go bindings.
#
#   ./build.sh            build, stage and regenerate
#   ./build.sh --check    additionally fail if the bindings on disk changed
#
# Requires a Rust toolchain (see rust-version in rust/Cargo.toml), Go, and
# uniffi-bindgen-go at the version pinned below:
#
#   cargo install uniffi-bindgen-go \
#     --git https://github.com/NordSecurity/uniffi-bindgen-go --tag v0.7.1+v0.31.0
#
# CARGO_BUILD_JOBS bounds the number of parallel compiler processes. The
# first build compiles about 300 crates.
set -euo pipefail

# The uniffi-bindgen-go release is tied to the uniffi version in
# rust/Cargo.toml. The two are bumped together.
BINDGEN_VERSION="0.7.1+v0.31.0"

cd "$(dirname "$0")"

check=""
case "${1:-}" in
"") ;;
--check) check=1 ;;
*)
	echo "usage: $0 [--check]" >&2
	exit 2
	;;
esac

for tool in cargo go uniffi-bindgen-go; do
	command -v "$tool" >/dev/null || {
		echo "$tool not found in PATH" >&2
		exit 1
	}
done
if ! uniffi-bindgen-go --version | grep -qF "$BINDGEN_VERSION"; then
	echo "uniffi-bindgen-go $BINDGEN_VERSION is required, found: $(uniffi-bindgen-go --version)" >&2
	exit 1
fi

goos=$(go env GOOS)
goarch=$(go env GOARCH)
case "$goos" in
linux) cdylib=libzeclib.so ;;
*)
	echo "unsupported platform: $goos/$goarch" >&2
	exit 1
	;;
esac

cargo build --release --locked --manifest-path rust/Cargo.toml

libdir="lib/${goos}-${goarch}"
mkdir -p "$libdir"
cmp -s rust/target/release/libzeclib.a "$libdir/libzeclib.a" ||
	cp rust/target/release/libzeclib.a "$libdir/libzeclib.a"

# uniffi-bindgen-go reads the interface from the metadata that the uniffi
# macros embed in the shared library. It writes <namespace>/<namespace>.go
# and a C header beside it. It locates the crate through cargo, so it runs
# from the crate directory.
out=$(mktemp -d)
trap 'rm -rf "$out"' EXIT
(cd rust && uniffi-bindgen-go --out-dir "$out" "target/release/$cdylib")

ffi=internal/ffi
{
	printf '// Code generated by uniffi-bindgen-go. DO NOT EDIT.\n\n//go:build zec\n\n'
	cat "$out/ffi/ffi.go"
} >"$out/ffi.go"

# A file is replaced only when its content changes. The comparison is with
# the file on disk, so --check also works before the bindings are tracked.
changed=""
install_generated() {
	if ! cmp -s "$1" "$2"; then
		cp "$1" "$2"
		changed="$changed $2"
	fi
}
install_generated "$out/ffi.go" "$ffi/ffi.go"
install_generated "$out/ffi/ffi.h" "$ffi/ffi.h"

# The go command does not track the contents of files named in cgo LDFLAGS,
# so a rebuilt library alone would not cause a relink. This untracked file
# changes with the library and is part of the package, which does.
stamp=$(sha256sum "$libdir/libzeclib.a" | cut -d' ' -f1)
cat >"$ffi/libstamp_${goos}_${goarch}.go" <<STAMP
// Code generated by build.sh. DO NOT EDIT.

//go:build zec

package ffi

// libStamp is the SHA-256 of the static library this package was last built
// against.
const libStamp = "${stamp}"
STAMP

if [ -n "$check" ] && [ -n "$changed" ]; then
	echo "the generated bindings were out of date and have been regenerated:$changed" >&2
	echo "commit the regenerated files" >&2
	exit 1
fi

echo "staged $libdir/libzeclib.a and regenerated $ffi"
