package bnb

import (
	"github.com/bisoncraft/caribou/util"
	dexeth "github.com/bisoncraft/caribou/wallet/asset/eth"
	"github.com/ethereum/go-ethereum/common"
)

const (
	MainnetChainID = 56
	TestnetChainID = 97
	SimnetChainID  = 1337
)

var (
	ChainIDs = map[util.Network]int64{
		util.Mainnet: MainnetChainID,
		util.Testnet: TestnetChainID,
		util.Simnet:  SimnetChainID,
	}

	UnitInfo = util.UnitInfo{
		AtomicUnit: "gwei",
		Conventional: util.Denomination{
			Unit:             "BNB",
			ConversionFactor: 1e9,
		},
		FeeRateDenom: "gas",
	}

	MultiBalanceAddresses = map[util.Network]common.Address{}

	usdcTokenID, _ = util.BipSymbolID("usdc.bnb")
	usdtTokenID, _ = util.BipSymbolID("usdt.bnb")

	// bep20StablecoinEVMFactor accounts for Binance-Peg USDC/USDT using 18
	// on-chain decimals, unlike their 6-decimal Ethereum counterparts:
	// log10(ConversionFactor=1e6) + 12 = 18.
	bep20StablecoinEVMFactor = int64(12)

	Tokens = map[uint32]*dexeth.Token{
		usdcTokenID: TokenUSDC,
		usdtTokenID: TokenUSDT,
	}

	// TokenUSDC is Binance-Peg USD Coin (BEP-20). Verified against
	// bscscan.com/blockscan.com token listings for the mainnet contract
	// (2026-07-13); the address previously here was missing its trailing
	// hex digit (39 chars instead of 40) and would not have been a valid
	// address at all.
	TokenUSDC = &dexeth.Token{
		EVMFactor: &bep20StablecoinEVMFactor,
		Token: &util.Token{
			NetworkID: BipID,
			Name:      "USDC",
			UnitInfo: util.UnitInfo{
				AtomicUnit: "µUSD",
				Conventional: util.Denomination{
					Unit:             "USDC",
					ConversionFactor: 1e6,
				},
				Alternatives: []util.Denomination{
					{
						Unit:             "cents",
						ConversionFactor: 1e2,
					},
				},
				FeeRateDenom: "gas",
			},
		},
		NetTokens: map[util.Network]*dexeth.NetToken{
			util.Mainnet: {
				// https://bscscan.com/token/0x8ac76a51cc950d9822d68b83fe1ad97b32cd580d
				Address: common.HexToAddress("0x8ac76a51cc950d9822d68b83fe1ad97b32cd580d"),
				// Not measured on BNB; borrowed from usdt.base mainnet measurements x1.3.
				// BEP-20 contracts use the same EVM opcodes, but these should be replaced
				// with BNB mainnet measurements.
				GasEstimate: &dexeth.Gases{
					Approve:  60_732,
					Transfer: 67_358,
				},
			},
			util.Simnet: {
				Address: common.Address{},
				// Not measured on BNB; borrowed from usdt.base mainnet measurements x1.3.
				// BEP-20 contracts use the same EVM opcodes, but these should be replaced
				// with BNB mainnet measurements.
				GasEstimate: &dexeth.Gases{
					Approve:  60_732,
					Transfer: 67_358,
				},
			},
		},
	}

	// TokenUSDT is Binance-Peg BSC-USD (BEP-20). Verified against
	// bscscan.com and the trustwallet/assets BEP-20 token list (2026-07-13).
	TokenUSDT = &dexeth.Token{
		EVMFactor: &bep20StablecoinEVMFactor,
		Token: &util.Token{
			NetworkID: BipID,
			Name:      "Tether",
			UnitInfo: util.UnitInfo{
				AtomicUnit: "microUSD",
				Conventional: util.Denomination{
					Unit:             "USDT",
					ConversionFactor: 1e6,
				},
			},
		},
		NetTokens: map[util.Network]*dexeth.NetToken{
			util.Mainnet: {
				// https://bscscan.com/token/0x55d398326f99059fF775485246999027B3197955
				Address: common.HexToAddress("0x55d398326f99059fF775485246999027B3197955"),
				// Not measured on BNB; borrowed from usdt.base mainnet measurements x1.3.
				// BEP-20 contracts use the same EVM opcodes, but these should be replaced
				// with BNB mainnet measurements.
				GasEstimate: &dexeth.Gases{
					Approve:  60_732,
					Transfer: 67_358,
				},
			},
			util.Simnet: {
				Address: common.Address{},
				// Not measured on BNB; borrowed from usdt.base mainnet measurements x1.3.
				// BEP-20 contracts use the same EVM opcodes, but these should be replaced
				// with BNB mainnet measurements.
				GasEstimate: &dexeth.Gases{
					Approve:  60_732,
					Transfer: 67_358,
				},
			},
		},
	}

	// simnetUSDC is the same NetToken as TokenUSDC's Simnet entry, kept as a
	// separate reference for provider-compatibility checks in chaincfg.go.
	simnetUSDC = TokenUSDC.NetTokens[util.Simnet]
)

// MaybeReadSimnetAddrs attempts to read the info files generated by the EVM
// simnet harness so provider-compatibility checks can use a deployed ERC20.
func MaybeReadSimnetAddrs() {
	dexeth.MaybeReadSimnetAddrsDir("bnb", MultiBalanceAddresses, simnetUSDC, Tokens[usdtTokenID].NetTokens[util.Simnet], nil, nil, nil)
}
