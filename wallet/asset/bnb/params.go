package bnb

import (
	"github.com/bisoncraft/bosswallet/util"
	dexeth "github.com/bisoncraft/bosswallet/wallet/asset/eth"
	"github.com/ethereum/go-ethereum/common"
)

const (
	MainnetChainID = 56
	TestnetChainID = 97
	SimnetChainID  = 1337
)

var (
	ChainIDs = map[util.Network]int64{
		util.Mainnet: MainnetChainID,
		util.Testnet: TestnetChainID,
		util.Simnet:  SimnetChainID,
	}

	UnitInfo = util.UnitInfo{
		AtomicUnit: "gwei",
		Conventional: util.Denomination{
			Unit:             "BNB",
			ConversionFactor: 1e9,
		},
		FeeRateDenom: "gas",
	}

	// v1Gases has zero gas estimates because no swap contracts are deployed for
	// BNB. Populate these when BNB tokens with swap support are added.
	v1Gases = &dexeth.Gases{}

	VersionedGases = map[uint32]*dexeth.Gases{
		1: v1Gases,
	}

	MultiBalanceAddresses = map[util.Network]common.Address{}

	simnetUSDC = &dexeth.NetToken{}
)

func init() {
	MaybeReadSimnetAddrs()
}

// MaybeReadSimnetAddrs attempts to read the info files generated by the EVM
// simnet harness so provider-compatibility checks can use a deployed ERC20.
func MaybeReadSimnetAddrs() {
	dexeth.MaybeReadSimnetAddrsDir("bnb", MultiBalanceAddresses, simnetUSDC, nil, nil, nil, nil)
}
