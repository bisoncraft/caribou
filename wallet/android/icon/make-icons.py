#!/usr/bin/env python3
"""Regenerates the launcher icon resources from wallet/ios/icon/appicon.svg,
the only vector copy of the antler mark in the tree.

    cd wallet/android/icon && ./make-icons.py

Writes, under app/src/main/res/:

  drawable/ic_launcher_foreground.xml   the mark as a vector drawable, used as
                                        the adaptive icon's foreground and as
                                        its monochrome (themed icon) layer
  mipmap-<density>/ic_launcher.png      raster fallbacks for API levels below
                                        26, which have no adaptive icons

The background layer (drawable/ic_launcher_background.xml) and the adaptive
icon itself (mipmap-anydpi-v26/ic_launcher.xml) are written by hand and are
not touched here.

An adaptive icon is a 108dp square of which only the middle 66dp circle is
guaranteed to survive a launcher's mask, so the mark is scaled until the
corners of its bounding box sit on that circle and is centered. The raster
fallbacks are the full iOS tile, which already carries its own ground and
inset. They need Inkscape on PATH.
"""

import math
import pathlib
import re
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
SVG = HERE / "../../ios/icon/appicon.svg"
RES = HERE / "../app/src/main/res"

VIEWPORT = 108.0
SAFE_DIAMETER = 66.0
# Launcher icon edge in pixels at each density (48dp at mdpi).
DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}

NUMBER = r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?"


def bounds(d):
    """Bounding box of a path made of move, line and close commands."""
    toks = re.findall(r"[A-Za-z]|" + NUMBER, d)
    x = y = sx = sy = 0.0
    xs, ys = [], []
    cmd = None
    i = 0
    while i < len(toks):
        if toks[i].isalpha():
            cmd = toks[i]
            i += 1
            if cmd in "zZ":
                x, y = sx, sy
            continue
        if cmd in "mMlL":
            a, b = float(toks[i]), float(toks[i + 1])
            i += 2
            x, y = (x + a, y + b) if cmd.islower() else (a, b)
            if cmd in "mM":
                sx, sy = x, y
                cmd = "l" if cmd == "m" else "L"
        elif cmd in "hH":
            a = float(toks[i])
            i += 1
            x = x + a if cmd == "h" else a
        elif cmd in "vV":
            a = float(toks[i])
            i += 1
            y = y + a if cmd == "v" else a
        else:
            sys.exit(f"path command {cmd!r} is not handled; extend bounds()")
        xs.append(x)
        ys.append(y)
    return min(xs), min(ys), max(xs), max(ys)


def main():
    svg = SVG.read_text()
    paths = []
    for m in re.finditer(r"<path(.*?)/>", svg, flags=re.S):
        attrs = m.group(1)
        d = " ".join(re.search(r'\sd="([^"]*)"', attrs, flags=re.S).group(1).split())
        fill = re.search(r"fill:(#[0-9a-fA-F]{6})", attrs).group(1)
        paths.append((fill, d))
    if not paths:
        sys.exit(f"no paths found in {SVG}")

    boxes = [bounds(d) for _, d in paths]
    x0 = min(b[0] for b in boxes)
    y0 = min(b[1] for b in boxes)
    x1 = max(b[2] for b in boxes)
    y1 = max(b[3] for b in boxes)
    scale = SAFE_DIAMETER / math.hypot(x1 - x0, y1 - y0)
    tx = VIEWPORT / 2 - scale * (x0 + x1) / 2
    ty = VIEWPORT / 2 - scale * (y0 + y1) / 2

    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by wallet/android/icon/make-icons.py from",
        "     wallet/ios/icon/appicon.svg. Do not edit by hand. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108">',
        "    <group",
        f'        android:scaleX="{scale:.5f}"',
        f'        android:scaleY="{scale:.5f}"',
        f'        android:translateX="{tx:.4f}"',
        f'        android:translateY="{ty:.4f}">',
    ]
    for fill, d in paths:
        out += ["        <path", f'            android:fillColor="{fill}"', f'            android:pathData="{d}" />']
    out += ["    </group>", "</vector>", ""]
    fg = RES / "drawable/ic_launcher_foreground.xml"
    fg.parent.mkdir(parents=True, exist_ok=True)
    fg.write_text("\n".join(out))
    print(f"wrote {fg.relative_to(HERE.parent)}: scale {scale:.5f}, {len(paths)} paths")

    for density, px in DENSITIES.items():
        png = RES / f"mipmap-{density}/ic_launcher.png"
        png.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(
            ["inkscape", str(SVG), "--export-type=png", f"--export-filename={png}", "-w", str(px), "-h", str(px)],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        print(f"wrote {png.relative_to(HERE.parent)} ({px}px)")


if __name__ == "__main__":
    main()
